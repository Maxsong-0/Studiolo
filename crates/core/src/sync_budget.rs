//! 同步平面一轮的两项预算：能比对的路径数（基线、canonical、镜像三方合计的不同路径，BUG-047），
//! 和能比对的内容字节数（三方「存在」内容各算一遍的合计）。
//!
//! 写者同步观察、镜像观察、范围并集、规划器预算与 Bridge 持久状态都只引用这里的值；
//! 路径预算原来各处各写一份 4096，只放宽一处会把失败挪到下一处。超过预算一律失败关闭，不分页、不截断。

/// 一轮同步三方合计的不同路径数上限；也是一批的输出项、Bridge 一批的动作数上限。
pub const SYNC_PATH_BUDGET: usize = 16_384;

/// 一轮同步里「存在」内容的字节合计上限（4 GiB）。范围并集把基线、canonical、镜像三组各算一遍后按它截止，
/// 写者观察对 canonical 一侧单独也按它截止；人侧批准前先拿三方合计和它比，把用量记进健康节。
pub const SYNC_BYTE_BUDGET: u64 = 4 * 1024 * 1024 * 1024;
